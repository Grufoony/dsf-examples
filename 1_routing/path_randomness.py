"""
Script to show how dsf plans routes and how path randomness spreads them, using the Router.
It times A* against Dijkstra, then plans the same trip for many agents with the 'length',
'traveltime' and 'datt' weights at increasing path randomness (sigma). The map shows how
the agents spread over the network for the weight and sigma picked in its menu; a figure
shows how many distinct routes they take and how much longer these really are.
Requires the edges GeoJSON file to be generated by the 0_cartography script.
"""

import argparse
import time
from collections import Counter
from pathlib import Path

import folium
import geopandas as gpd
import matplotlib.pyplot as plt
import numpy as np
from branca.element import MacroElement
from dsf import logging
from dsf.mobility import Dynamics, RoadNetwork, RouteAlgorithm, RouteWeights
from folium.plugins import AntPath
from jinja2 import Template

INPUT_DIR = Path("../0_cartography/output")
OUTPUT_DIR = Path("output")

WEIGHTS = ("length", "traveltime", "datt")
COLOR = "blue"
# The agents plan on the weight of setEdgeWeight, as intelligent agents do
ROUTE_WEIGHTS = RouteWeights.CURRENT


class ComboSelector(MacroElement):
    """A map menu with a weight and a sigma radio group, showing the layer of the pair."""

    _template = Template(
        """
{% macro script(this, kwargs) %}
(function () {
    var map = {{ this._parent.get_name() }};
    var layers = {
    {%- for key, layer in this.layers.items() %}
        {{ key|tojson }}: {{ layer.get_name() }},
    {%- endfor %}
    };
    var options = {weight: {{ this.weights|tojson }}, sigma: {{ this.sigmas|tojson }}};
    var titles = {weight: "Weight", sigma: "Path randomness σ"};
    var selected = {weight: {{ this.weight|tojson }}, sigma: {{ this.sigma|tojson }}};

    function show() {
        Object.values(layers).forEach(function (layer) { map.removeLayer(layer); });
        layers[selected.weight + "|" + selected.sigma].addTo(map);
    }
    function radios(name) {
        var html = "<b>" + titles[name] + "</b>";
        options[name].forEach(function (value) {
            html += '<label style="display:block"><input type="radio" name="' + name
                + '" value="' + value + '"' + (value === selected[name] ? " checked" : "")
                + "> " + value + "</label>";
        });
        return html;
    }

    var control = L.control({position: "topright"});
    control.onAdd = function () {
        var div = L.DomUtil.create(
            "div", "leaflet-control-layers leaflet-control-layers-expanded");
        div.innerHTML = radios("weight")
            + '<div class="leaflet-control-layers-separator"></div>' + radios("sigma");
        L.DomEvent.disableClickPropagation(div);
        L.DomEvent.on(div, "change", function (event) {
            selected[event.target.name] = event.target.value;
            show();
        });
        return div;
    };
    control.addTo(map);
    show();
})();
{% endmacro %}
"""
    )

    def __init__(self, layers, weights, sigmas, weight, sigma):
        super().__init__()
        self._name = "ComboSelector"
        self.layers = {f"{w}|{s}": layer for (w, s), layer in layers.items()}
        self.weights = list(weights)
        self.sigmas = [str(s) for s in sigmas]
        self.weight = weight
        self.sigma = str(sigma)


def street_coords(edges: gpd.GeoDataFrame, street_id: int) -> list[tuple[float, float]]:
    """Get the (lat, lon) coordinates of a street, as folium wants them."""
    return [(lat, lon) for lon, lat in edges.loc[street_id, "geometry"].coords]


def route_coords(edges: gpd.GeoDataFrame, route) -> list[tuple[float, float]]:
    """Get the (lat, lon) coordinates of a route as one line, in the direction of travel."""
    coords = []
    for street_id in route:
        street = street_coords(edges, street_id)
        # Consecutive streets share the junction between them
        coords.extend(street[1:] if coords and coords[-1] == street[0] else street)
    return coords


def pick_trip(router, edges: gpd.GeoDataFrame, seed: int, min_streets: int):
    """Pick a random origin and destination street, far enough and connected."""
    rng = np.random.default_rng(seed)
    ids = edges.index.to_numpy()
    for _ in range(1000):
        origin, goal = (int(i) for i in rng.choice(ids, size=2, replace=False))
        if len(router.route(origin, goal, ROUTE_WEIGHTS)) >= min_streets:
            return origin, goal
    raise RuntimeError("No connected trip found: is the network strongly connected?")


def compare_weights(dynamics, router, edges, origin, goal, distance_cost):
    """Log the length and free-flow time of the best route of each weight."""
    routes = {}
    for weight in WEIGHTS:
        dynamics.setEdgeWeight(weight, distance_cost)
        routes[weight] = router.route(origin, goal, ROUTE_WEIGHTS)
    # With 'datt' every agent also pays the distance cost, free-flow ones included: measure
    # the free-flow times with 'traveltime' set
    dynamics.setEdgeWeight("traveltime")
    for weight, route in routes.items():
        # routeCost counts the streets travelled, i.e. all but the first
        length_km = edges.loc[route[1:], "length"].sum() / 1e3
        free_flow_min = router.routeCost(route, RouteWeights.FREE_FLOW) / 60
        logging.info(
            f"'{weight}': {len(route)} streets, {length_km:.2f} km, "
            f"{free_flow_min:.1f} min at free flow"
        )


def compare_algorithms(dynamics, router, edges, seed, n_queries):
    """Time A* against Dijkstra on the same random trips and check they agree."""
    rng = np.random.default_rng(seed + 1)
    pairs = rng.choice(edges.index.to_numpy(), size=(n_queries, 2))
    costs, timings = {}, {}
    for algorithm in (RouteAlgorithm.DIJKSTRA, RouteAlgorithm.ASTAR):
        dynamics.setRouteAlgorithm(algorithm)
        start = time.perf_counter()
        routes = [router.route(int(a), int(b), ROUTE_WEIGHTS) for a, b in pairs]
        timings[algorithm] = (time.perf_counter() - start) / n_queries * 1e3
        costs[algorithm] = np.array(
            [router.routeCost(r, ROUTE_WEIGHTS) if r else np.nan for r in routes]
        )
    gap = np.nanmax(
        np.abs(costs[RouteAlgorithm.ASTAR] - costs[RouteAlgorithm.DIJKSTRA])
    )
    logging.info(
        f"{n_queries} queries: Dijkstra {timings[RouteAlgorithm.DIJKSTRA]:.2f} ms, "
        f"A* {timings[RouteAlgorithm.ASTAR]:.2f} ms per route "
        f"(heuristic: {router.hasHeuristic()}), largest cost gap {gap:.2e}"
    )


def spread_routes(dynamics, router, origin, goal, distance_cost, sigmas, n_agents):
    """Plan the trip for n_agents agents with each weight, at each sigma.

    Returns, for each (weight, sigma) pair, the share of agents using each street, the
    number of distinct routes, the true cost overhead (cost / optimum - 1) of every agent's
    route, on that weight, and the most common route with its share of the agents.
    """
    results = {}
    for weight in WEIGHTS:
        dynamics.setEdgeWeight(weight, distance_cost)
        dynamics.setPathRandomness(0.0)
        best = router.route(origin, goal, ROUTE_WEIGHTS)
        best_cost = router.routeCost(best, ROUTE_WEIGHTS)
        for sigma in sigmas:
            dynamics.setPathRandomness(sigma)
            # Any integer is an agent key: different keys behave as different agents
            routes = [
                router.route(origin, goal, ROUTE_WEIGHTS, key)
                for key in range(n_agents)
            ]
            # The true cost of a route is its cost without noise
            dynamics.setPathRandomness(0.0)
            overhead = np.array(
                [router.routeCost(r, ROUTE_WEIGHTS) / best_cost - 1 for r in routes]
            )
            usage = Counter(street for route in routes for street in route)
            route_counts = Counter(tuple(route) for route in routes)
            top_route, top_count = route_counts.most_common(1)[0]
            results[weight, sigma] = {
                "share": {street: n / n_agents for street, n in usage.items()},
                "distinct": len(route_counts),
                "overhead": overhead,
                "top_route": list(top_route),
                "top_share": top_count / n_agents,
            }
            logging.info(
                f"'{weight}', sigma = {sigma}: {len(route_counts)} distinct route(s) over "
                f"{n_agents} agents, mean overhead {overhead.mean():.1%}, "
                f"worst {overhead.max():.1%}"
            )
    dynamics.setPathRandomness(0.0)
    return results


def map_spread(edges, results, fmap):
    """Make a layer per (weight, sigma) pair, hidden until the menu picks it.

    Each street is as thick as the share of agents using it, and the most common route
    marches on top of it, from the origin to the destination.
    """
    layers = {}
    for (weight, sigma), result in results.items():
        group = folium.FeatureGroup(
            name=f"'{weight}', sigma {sigma}", show=False, control=False
        )
        for street_id, share in result["share"].items():
            folium.PolyLine(
                street_coords(edges, street_id),
                color=COLOR,
                weight=1 + 9 * share,
                opacity=0.3 + 0.6 * share,
                tooltip=f"Street {street_id}: {share:.0%} of the agents",
            ).add_to(group)
        AntPath(
            route_coords(edges, result["top_route"]),
            color=COLOR,
            pulse_color="#FFFFFF",
            weight=4,
            delay=800,
            dash_array=[10, 20],
            tooltip=f"Most common route: {result['top_share']:.0%} of the agents",
        ).add_to(group)
        group.add_to(fmap)
        layers[weight, sigma] = group
    return layers


def plot_spread(results, sigmas, n_agents, path: Path):
    """Plot the number of distinct routes and the cost overhead against sigma."""
    fig, (ax_routes, ax_cost) = plt.subplots(
        1, 2, figsize=(10, 4), layout="constrained"
    )
    for weight in WEIGHTS:
        overheads = [100 * results[weight, s]["overhead"] for s in sigmas]
        ax_routes.plot(
            sigmas, [results[weight, s]["distinct"] for s in sigmas], "o-", label=weight
        )
        (line,) = ax_cost.plot(
            sigmas, [o.mean() for o in overheads], "o-", label=weight
        )
        ax_cost.fill_between(
            sigmas,
            [np.percentile(o, 10) for o in overheads],
            [np.percentile(o, 90) for o in overheads],
            color=line.get_color(),
            alpha=0.15,
        )
    ax_routes.set(
        xlabel=r"Path randomness $\sigma$",
        ylabel=f"Distinct routes over {n_agents} agents",
    )
    ax_cost.set(
        xlabel=r"Path randomness $\sigma$",
        ylabel="True cost overhead (%)",
        title="Mean, band from the 10th to the 90th percentile",
    )
    for ax in (ax_routes, ax_cost):
        ax.grid(alpha=0.3)
        ax.legend()
    fig.savefig(path)
    plt.close(fig)


def main(
    weight: str = "traveltime",
    distance_cost: float = 0.1,
    sigmas: tuple[float, ...] = (0.0, 0.1, 0.3, 0.6),
    n_agents: int = 500,
    seed: int = 13156,
):
    if not (INPUT_DIR / "edges.geojson").exists():
        logging.error(
            f"Edges GeoJSON file not found in {INPUT_DIR}. Please run the 0_cartography script first."
        )
        return
    edges = gpd.read_file(INPUT_DIR / "edges.geojson").set_index("id")

    road_network = RoadNetwork()
    road_network.importEdges((INPUT_DIR / "edges.geojson").as_posix())
    # The dynamics owns the network and its router: the router is a read-only view of it
    dynamics = Dynamics(road_network, seed=seed)
    router = dynamics.router()
    logging.info(f"Router built on {router.nEdges()} streets")

    origin, goal = pick_trip(router, edges, seed, min_streets=15)
    logging.info(f"Trip from street {origin} to street {goal}")

    # 1. The weights and the algorithms
    compare_weights(dynamics, router, edges, origin, goal, distance_cost)
    compare_algorithms(dynamics, router, edges, seed, n_queries=200)

    # 2. The effect of noise, for each weight
    results = spread_routes(
        dynamics, router, origin, goal, distance_cost, sigmas, n_agents
    )

    min_lon, min_lat, max_lon, max_lat = edges.total_bounds
    fmap = folium.Map(
        location=[(min_lat + max_lat) / 2, (min_lon + max_lon) / 2], zoom_start=14
    )
    layers = map_spread(edges, results, fmap)
    # The map opens on the noiseless best route of the chosen weight
    ComboSelector(layers, WEIGHTS, sigmas, weight, sigmas[0]).add_to(fmap)
    for street_id, label, color in (
        (origin, "Origin", "green"),
        (goal, "Destination", "red"),
    ):
        folium.Marker(
            street_coords(edges, street_id)[-1 if street_id == goal else 0],
            tooltip=f"{label}: street {street_id}",
            icon=folium.Icon(color=color),
        ).add_to(fmap)
    fmap.save(OUTPUT_DIR / "path_randomness.html")
    plot_spread(results, sigmas, n_agents, OUTPUT_DIR / "path_randomness.pdf")
    logging.info(
        f"Saved {OUTPUT_DIR / 'path_randomness.html'} and {OUTPUT_DIR / 'path_randomness.pdf'}"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Show the routing weights and the effect of path randomness."
    )
    parser.add_argument(
        "--weight",
        help="The weight the map opens on (default: traveltime).",
        choices=WEIGHTS,
        default="traveltime",
    )
    parser.add_argument(
        "--distance-cost",
        help="The cost of a metre of the 'datt' weight, in s/m (default: 0.1).",
        type=float,
        default=0.1,
    )
    parser.add_argument(
        "--sigmas",
        help="The path randomness values to compare, the map opening on the first "
        "(default: 0 0.1 0.3 0.6).",
        type=float,
        nargs="+",
        default=[0.0, 0.1, 0.3, 0.6],
    )
    parser.add_argument(
        "--agents",
        help="The number of agents planning the trip at each sigma (default: 500).",
        type=int,
        default=500,
    )
    parser.add_argument(
        "--seed",
        help="The random seed to use (default: 69).",
        type=int,
        default=69,
    )
    args = parser.parse_args()
    OUTPUT_DIR.mkdir(exist_ok=True)
    main(args.weight, args.distance_cost, tuple(args.sigmas), args.agents, args.seed)
